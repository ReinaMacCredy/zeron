use std::path::{Path, PathBuf};
use std::process::{Command, Stdio};

pub const PLAYBOOK: &str = include_str!("../../../.github/triage/PLAYBOOK.md");
pub const PLAYBOOK_FILE: &str = "triage-playbook.md";
pub const CONTEXT_FILE: &str = "triage-context.md";
const SOURCE_FILE: &str = "source.md";
pub const REPO: &str = "https://github.com/ReinaMacCredy/zeron";
const AGENT_CLIS: [(&str, &str); 6] = [
    ("Claude Code", "claude"),
    ("Codex", "codex"),
    ("Cursor", "cursor-agent"),
    ("OpenCode", "opencode"),
    ("Gemini", "gemini"),
    ("GitHub CLI", "gh"),
];

#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum Entry {
    App,
    Cli,
}

#[derive(Clone, Debug)]
pub struct Prepared {
    pub dir: PathBuf,
    pub playbook: PathBuf,
    pub context: PathBuf,
}

pub fn triage_root(data_dir: &Path) -> PathBuf {
    data_dir.join("triage")
}

pub fn source_cache_dir(data_dir: &Path) -> PathBuf {
    triage_root(data_dir).join("source")
}

pub fn prepare(data_dir: &Path) -> std::io::Result<Prepared> {
    let stamp = chrono::Local::now().format("%Y%m%d-%H%M%S");
    let root = triage_root(data_dir);
    let dir = (1..)
        .map(|n| match n {
            1 => root.join(stamp.to_string()),
            n => root.join(format!("{stamp}-{n}")),
        })
        .find(|dir| !dir.exists())
        .expect("an unused folder");
    std::fs::create_dir_all(&dir)?;
    std::fs::create_dir_all(source_cache_dir(data_dir))?;
    let playbook = dir.join(PLAYBOOK_FILE);
    std::fs::write(&playbook, PLAYBOOK)?;
    Ok(Prepared {
        context: dir.join(CONTEXT_FILE),
        dir,
        playbook,
    })
}

// Slow: probes every agent CLI's version, so the app runs it off the main thread.
pub fn write_context(
    data_dir: &Path,
    prepared: &Prepared,
    entry: Entry,
    build: Option<&str>,
    cloning: bool,
) -> std::io::Result<()> {
    let report = cloning.then(|| prepared.dir.join(SOURCE_FILE));
    std::fs::write(
        &prepared.context,
        context_text(data_dir, entry, build, report),
    )
}
pub fn spawn_app_background(data_dir: PathBuf, prepared: &Prepared, build: Option<&'static str>) {
    let prepared = prepared.clone();
    std::thread::spawn(move || {
        let _ = write_context(&data_dir, &prepared, Entry::App, build, true);
        clone_source_into(&data_dir, &prepared.dir);
    });
}

fn context_text(
    data_dir: &Path,
    entry: Entry,
    build: Option<&str>,
    source_report: Option<PathBuf>,
) -> String {
    let version = zeron_update::current_version();
    let show = |path: PathBuf| path.to_string_lossy().into_owned();
    let at = |path: PathBuf| {
        let missing = if path.exists() { "" } else { " (not present)" };
        format!("{}{missing}", path.to_string_lossy())
    };
    let install = match zeron_update::detect_install() {
        zeron_update::InstallKind::Managed { .. } => "managed install (`zeron update`)",
        zeron_update::InstallKind::MacApp { .. } => "macOS app bundle",
        #[cfg(windows)]
        zeron_update::InstallKind::WindowsPortable { .. } => "Windows install",
        zeron_update::InstallKind::Unmanaged => "source build or copied binary",
    };
    let profile = if cfg!(debug_assertions) {
        "debug"
    } else {
        "release"
    };
    let engine = match crate::InstanceLock::holder(data_dir) {
        Some(pid) => format!("running (pid {pid})"),
        None => "not running".into(),
    };
    let started = match entry {
        Entry::App => "\"Triage an issue\" in the Zeron app",
        Entry::Cli => "`zeron triage` in a terminal",
    };
    let mut out = format!(
        "# Zeron triage context\n\n\
         Generated by {started} at {}.\n\n\
         - Zeron version: {version} (the build that wrote this file; the bug may have happened on another)\n\
         - Build: {profile}, {install}{}\n\
         - Release tag to clone: v{version} (if it does not exist, clone main)\n\
         - OS: {} {}\n\
         - Engine: {engine}\n\
         - Repo: {REPO} (fork of https://github.com/zeronsh/zeron)\n",
        chrono::Local::now().to_rfc3339(),
        build
            .map(|hash| format!(", commit {hash}"))
            .unwrap_or_default(),
        std::env::consts::OS,
        std::env::consts::ARCH,
    );
    if entry == Entry::App {
        out.push_str(
            "\n## This session runs inside Zeron\n\n\
             You are a chat inside the Zeron app described above. Quitting or restarting the\n\
             app or its engine ends this session. When a fix needs that, give the user the\n\
             exact steps and let them do it. The engine has the database open: read it, never\n\
             lock it.\n",
        );
    }
    if let Some(report) = source_report {
        out.push_str(&format!(
            "\n## Source\n\n\
             Zeron started cloning its own source in the background. When the clone finishes\n\
             or fails it writes {} naming the folder and commit, or why it failed. Wait for\n\
             that file instead of cloning again; if it has not appeared after a few minutes,\n\
             clone as step 4 describes. When the bug happened on another build, clone that\n\
             version instead.\n",
            show(report)
        ));
    }
    out.push_str("\n## Installed agent CLIs\n\n");
    for (name, exe) in AGENT_CLIS {
        let line = match zeron_harness::installed_cli(exe) {
            Some((path, Some(version))) => format!("{version} at {}", show(path)),
            Some((path, None)) => format!("version unknown, at {}", show(path)),
            None => "not found on PATH".into(),
        };
        out.push_str(&format!("- {name} (`{exe}`): {line}\n"));
    }
    let logs = data_dir.join("logs");
    out.push_str(&format!(
        "\n## Paths\n\n\
         - Data dir: {}\n\
         - Logs dir: {} (`zeron-headed.log` for the app, `zeron-engine.log` for the background engine, `zeron-headless.log` for `zeron headless`; `.old` is the rotated copy)\n\
         - Daemon log (`zeron daemon` installs only): {}\n\
         - Database, local workspace (SQLite; write only with the user's explicit permission): {}\n\
         - Database, signed-in workspaces: `docs.sqlite3` under {} (one folder per org and account)\n\
         - Run journals: `journals` next to each database\n\
         - App settings: {}\n\
         - Composer defaults: {}\n\
         - Harness preferences: {}\n\
         - Projects cloned by Zeron: {}\n\
         - Playbooks (all projects): {}\n\
         - Source cache dir (clone the repo here): {}\n\
         \n\
         ## Never read\n\n\
         These hold sign-in sessions, tokens and provider credentials:\n\n\
         - {}\n\
         - {}\n\
         - {}\n\
         - {}\n",
        at(data_dir.to_path_buf()),
        at(logs),
        at(data_dir.join("daemon.log")),
        at(data_dir.join("profiles").join("local").join("docs.sqlite3")),
        at(data_dir.join("orgs")),
        at(data_dir.join("ui-settings.json")),
        at(data_dir.join("composer-defaults.json")),
        at(data_dir.join("harness-prefs.json")),
        at(data_dir.join("repos")),
        at(crate::playbooks::app_dir(data_dir)),
        at(source_cache_dir(data_dir)),
        at(data_dir.join("session.json")),
        at(data_dir.join("cloud")),
        at(data_dir.join("agent-accounts")),
        at(data_dir.join("provider-homes")),
    ));
    out
}

pub fn launch_prompt(prepared: &Prepared) -> String {
    format!(
        "Read the file \"{}\" and follow its instructions exactly: it is your Zeron triage playbook, and it starts with asking the user what went wrong. Machine facts are in \"{}\".",
        prepared.playbook.to_string_lossy(),
        prepared.context.to_string_lossy()
    )
}
pub fn terminal_agents() -> Vec<(&'static str, PathBuf)> {
    [("Claude Code", "claude"), ("Codex", "codex")]
        .into_iter()
        .filter_map(|(name, exe)| Some((name, zeron_harness::installed_cli(exe)?.0)))
        .collect()
}

pub fn spawn_source_clone(data_dir: &Path, dir: &Path) {
    let (data_dir, dir) = (data_dir.to_path_buf(), dir.to_path_buf());
    std::thread::spawn(move || clone_source_into(&data_dir, &dir));
}
pub fn clone_source_into(data_dir: &Path, dir: &Path) {
    let text = match clone_source(&source_cache_dir(data_dir)) {
        Ok((folder, git_ref, commit)) => format!(
            "# Source\n\n{}  ({git_ref}, commit {commit})\n{}",
            folder.to_string_lossy(),
            if git_ref == "main" {
                "\nThis version has no release tag, so this is main: treat file and line\nreferences as approximate.\n"
            } else {
                ""
            }
        ),
        Err(reason) => format!(
            "# Source\n\nZeron could not clone its source: {reason}\nClone it as step 4 of the playbook describes.\n"
        ),
    };
    let _ = std::fs::write(dir.join(SOURCE_FILE), text);
}

fn clone_source(cache: &Path) -> Result<(PathBuf, String, String), String> {
    let tag = format!("v{}", zeron_update::current_version());
    let (git_ref, commit) = match remote_commit(&format!("refs/tags/{tag}"))? {
        Some(commit) => (tag, commit),
        None => (
            "main".to_string(),
            remote_commit("refs/heads/main")?.ok_or("main not found")?,
        ),
    };
    let folder = cache.join(&commit);
    if folder.is_dir() {
        return Ok((folder, git_ref, commit));
    }
    let partial = cache.join(format!(".{commit}.partial"));
    let _ = std::fs::remove_dir_all(&partial);
    let status = Command::new("git")
        .args([
            "clone",
            "--quiet",
            "--depth",
            "1",
            "--filter=blob:none",
            "--branch",
        ])
        .arg(&git_ref)
        .arg(REPO)
        .arg(&partial)
        .stdin(Stdio::null())
        .stdout(Stdio::null())
        .stderr(Stdio::null())
        .status()
        .map_err(|error| format!("git did not start: {error}"))?;
    if !status.success() {
        let _ = std::fs::remove_dir_all(&partial);
        return Err(format!("git clone exited with {status}"));
    }
    std::fs::rename(&partial, &folder).map_err(|error| error.to_string())?;
    Ok((folder, git_ref, commit))
}

fn remote_commit(git_ref: &str) -> Result<Option<String>, String> {
    let out = Command::new("git")
        .args(["ls-remote", REPO, git_ref])
        .stdin(Stdio::null())
        .stderr(Stdio::null())
        .output()
        .map_err(|error| format!("git did not start: {error}"))?;
    if !out.status.success() {
        return Err(format!("git ls-remote exited with {}", out.status));
    }
    Ok(String::from_utf8_lossy(&out.stdout)
        .split_whitespace()
        .next()
        .map(str::to_string))
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn prepare_writes_playbook_and_facts_without_secrets() {
        let data = tempfile::tempdir().unwrap();
        let first = prepare(data.path()).unwrap();
        write_context(data.path(), &first, Entry::Cli, Some("abc12345"), false).unwrap();
        let second = prepare(data.path()).unwrap();
        write_context(data.path(), &second, Entry::App, None, true).unwrap();
        assert_ne!(first.dir, second.dir);
        assert_eq!(std::fs::read_to_string(&first.playbook).unwrap(), PLAYBOOK);
        let cli = std::fs::read_to_string(&first.context).unwrap();
        assert!(cli.contains("`zeron triage` in a terminal"));
        assert!(cli.contains("commit abc12345"));
        assert!(!cli.contains("## Source"));
        assert!(!cli.contains("runs inside Zeron"));
        let app = std::fs::read_to_string(&second.context).unwrap();
        assert!(app.contains("## This session runs inside Zeron"));
        assert!(app.contains(&second.dir.join("source.md").to_string_lossy().into_owned()));
        assert!(app.contains(&source_cache_dir(data.path()).to_string_lossy().into_owned()));
        assert!(source_cache_dir(data.path()).is_dir());
        assert!(!app.contains('@'));
    }
}
