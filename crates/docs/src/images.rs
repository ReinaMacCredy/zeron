pub fn image(name: &str) -> Option<&'static [u8]> {
    IMAGES
        .iter()
        .find(|(candidate, _)| *candidate == name)
        .map(|(_, bytes)| *bytes)
}

/// Width and height from a JPEG's start-of-frame segment.
pub fn image_size(name: &str) -> Option<(u32, u32)> {
    let bytes = image(name)?;
    let mut at = 2;
    while at + 9 < bytes.len() {
        if bytes[at] != 0xFF {
            return None;
        }
        let marker = bytes[at + 1];
        let len = u16::from_be_bytes([bytes[at + 2], bytes[at + 3]]) as usize;
        if (0xC0..=0xC3).contains(&marker) {
            let height = u16::from_be_bytes([bytes[at + 5], bytes[at + 6]]) as u32;
            let width = u16::from_be_bytes([bytes[at + 7], bytes[at + 8]]) as u32;
            return (width > 0 && height > 0).then_some((width, height));
        }
        at += 2 + len;
    }
    None
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn every_referenced_image_is_bundled_with_a_size() {
        let changelog = crate::changelog::entries().iter().flat_map(|entry| {
            entry
                .hero
                .iter()
                .chain(entry.features.iter().filter_map(|f| f.image.as_ref()))
                .map(String::as_str)
        });
        let docs = crate::BODIES.iter().flat_map(|(_, body)| {
            body.lines().filter_map(|line| {
                line.trim_start()
                    .strip_prefix("![")?
                    .split_once("](")?
                    .1
                    .strip_suffix(')')
            })
        });
        let names: Vec<&str> = changelog.chain(docs).collect();
        assert!(names.len() > 40);
        assert_eq!(image_size("models-compact-picker.jpg"), Some((760, 256)));
        for name in names {
            assert!(image_size(name).is_some(), "{name} has no bundled size");
        }
    }
}
